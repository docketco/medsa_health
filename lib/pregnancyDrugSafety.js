function normalize(s) {
  return (s || '').toLowerCase().trim()
}

const FLAT_INDEX = PREGNANCY_DRUG_SAFETY_CATEGORIES.flatMap(cat =>
  cat.drugs.map(d => ({ ...d, category: cat.category }))
)

// Substring match against the display name (which already includes any
// brand name in parentheses, and either side of a "/" for a combined
// entry) - no fuzzy/AI matching, so a miss is a real miss, not a guess.
export function searchPregnancyDrugSafety(query) {
  const q = normalize(query)
  if (!q) return []
  return FLAT_INDEX.filter(d => normalize(d.name).includes(q))
}
